"""Generate router artifacts for the macaulay2 skill from an INSTALLED Macaulay2
documentation tree (version-pinned by construction -- we never scrape the web).

Scope: Macaulay2Doc (core) PLUS every package the kernel loads by default —
detected at RUNTIME from the actual binary (`loadedPackages`), not from a
hardcoded list. A symbol absent from the core index may live in a default
package's docs (verified 2026-10-11: primaryDecomposition, saturate,
integralClosure, minimalPrimes, tangentCone, ... all work at t=0 with 0 core
index rows).

Outputs (written into skills/macaulay2/references/):
  index.tsv    symbol <TAB> blurb <TAB> page <TAB> source-package   (master.html
               of every tree in scope)
  toc.md       nested thematic outline (core Macaulay2Doc)            (from toc.html)
  packages.md  bundled packages grouped by theme, ⚡ = default-loaded,
               ⭐ = refereed
"""

from __future__ import annotations

import argparse
import datetime
import html
import re
import subprocess
import sys
import tempfile
from pathlib import Path

DOC_SUBPATH = Path("share/doc/Macaulay2/Macaulay2Doc/html")
PACKAGES_PAGE = "_packages_spprovided_spwith_sp__Macaulay2.html"


def find_docs_root(m2_bin: str) -> Path:
    """Find the Macaulay2Doc html tree near the binary, trying common prefixes."""
    import shutil

    resolved = shutil.which(m2_bin) or m2_bin
    real = Path(resolved)
    try:
        real = real.resolve()
    except OSError:
        pass
    candidates = []
    for p in (real, Path(resolved)):
        candidates.append(p.parent.parent / DOC_SUBPATH)
    candidates += [
        Path("/opt/homebrew") / DOC_SUBPATH,
        Path("/usr/local") / DOC_SUBPATH,
    ]
    for cand in candidates:
        if cand.is_dir():
            return cand
    sys.exit(
        "error: docs tree not found (tried: "
        + ", ".join(str(c) for c in candidates)
        + "); pass --docs explicitly"
    )


def m2_version(m2_bin: str) -> str:
    out = subprocess.run([m2_bin, "--version"], capture_output=True, text=True).stdout
    m = re.search(r"(\d+\.\d+(?:\.\d+)?)", out)
    if not m:
        sys.exit(f"error: could not parse M2 version from: {out!r}")
    return m.group(1)


def run_m2_batch(m2_bin: str, code: str) -> str:
    with tempfile.NamedTemporaryFile("w", suffix=".m2", delete=False) as f:
        f.write(code)
        path = f.name
    proc = subprocess.run(
        [m2_bin, "-q", "--no-debug", "--no-tty", "--silent", "--stop", path],
        capture_output=True, text=True, timeout=300, stdin=subprocess.DEVNULL,
    )
    Path(path).unlink(missing_ok=True)
    return proc.stdout + proc.stderr


def default_loaded(m2_bin: str) -> list[str]:
    """Runtime truth: which packages the kernel loads at startup.

    Idiom notes (all verified on 1.26, the hard way):
      - `loadedPackages` is a List of Package objects (NO parens; parens give
        an adjacent-objects error), `installedPackages()` is a function.
      - Package objects have no .name field and no sort method (`?` error);
        map with `toString p` and sort the strings.
      - `print sort (...)` dangles: a statement ending in an operator name
        waits for continuation -- keep `print (expr)` parenthesized.
    """
    out = run_m2_batch(
        m2_bin,
        "L = for p in loadedPackages list toString p\n"
        'print (toExternalString (sort L))\n',
    )
    m = re.search(r"\{[^{}]*\}", out, re.S)
    if not m:
        sys.exit(f"error: could not read default-loaded packages from:\n{out[:800]}")
    names = re.findall(r"[A-Za-z0-9_]+", m.group(0))
    if not names:
        sys.exit(f"error: parsed empty package list from: {m.group(0)!r}")
    return names


def trees_in_scope(docs_root: Path, loaded: list[str]) -> list[tuple[str, Path]]:
    """(package, master.html dir) pairs: core + every default-loaded package
    that ships a docs tree. 'Core' is documented by the Macaulay2Doc tree."""
    base = docs_root.parent.parent  # .../share/doc/Macaulay2
    pairs: list[tuple[str, Path]] = [("Macaulay2Doc", docs_root)]
    for pkg in loaded:
        if pkg in ("Core", "Macaulay2Doc"):
            continue
        d = base / pkg / "html"
        if (d / "master.html").is_file():
            pairs.append((pkg, d))
        else:
            print(f"warn: default-loaded {pkg} has no docs tree at {d}", file=sys.stderr)
    return pairs


def header(kind: str, version: str, src: Path, loaded: list[str]) -> str:
    date = datetime.date.today().isoformat()
    return (
        f"# GENERATED by tools/mk_skill.py -- DO NOT EDIT BY HAND\n"
        f"# artifact: {kind} | source: Macaulay2 {version} docs at {src}\n"
        f"# default-loaded packages (runtime-detected, {len(loaded)}): {', '.join(loaded)}\n"
        f"# generated: {date}\n"
        f"# full doc page: $PREFIX/share/doc/Macaulay2/<PKG>/html/<page> (macaulay2.com\n"
        f"#   mirrors this layout; <PKG> = 4th column, Macaulay2Doc for core)\n"
        f"# CAVEAT: master.html indexes PAGE TITLES, so aliases (res -> freeResolution)\n"
        f"#   and symbols documented inside multi-topic pages may be absent -- a miss\n"
        f"#   means SUSPECT, not dead; confirm with m2_help, which resolves real bindings.\n"
    )


# ---------------------------------------------------------------- index.tsv

INDEX_RE = re.compile(
    r'<li><span><a(?:\s+title="([^"]*)")?\s+href="([^"]+)">(.*?)</a>(?:\s*--\s*(.*?))?</span></li>'
)


def gen_index(pairs: list[tuple[str, Path]]) -> str:
    rows, seen = [], set()
    for pkg, tree in pairs:
        text = (tree / "master.html").read_text(errors="replace")
        for title, href, sym, tail in INDEX_RE.findall(text):
            symbol = html.unescape(re.sub(r"<[^>]+>", "", sym)).strip()
            blurb = html.unescape(re.sub(r"<[^>]+>", "", tail or title or "")).strip()
            blurb = " ".join(blurb.split())
            key = (symbol, href, blurb, pkg)
            if key in seen or not symbol:
                continue
            seen.add(key)
            rows.append(f"{symbol}\t{blurb}\t{html.unescape(href)}\t{pkg}")
    return "\n".join(rows) + "\n"


# -------------------------------------------------------------------- toc.md

TOC_TOKEN_RE = re.compile(
    r"<ul>|</ul>|<li><span><a(?:\s+title=\"[^\"]*\")?\s+href=\"([^\"]+)\">(.*?)</a>(?:\s*--\s*(.*?))?</span>"
)


def gen_toc(src: Path) -> str:
    raw = (src / "toc.html").read_text(errors="replace")
    body = raw.split("<h1>", 1)[1].split(">", 1)[1]  # skip header/buttons
    out, depth = [], 0
    for m in TOC_TOKEN_RE.finditer(body):
        tok = m.group(0)
        if tok == "<ul>":
            depth += 1
            continue
        if tok == "</ul>":
            depth -= 1
            continue
        href, title, blurb = m.group(1), m.group(2), m.group(3) or ""
        title = html.unescape(re.sub(r"<[^>]+>", "", title)).strip()
        blurb = " ".join(html.unescape(re.sub(r"<[^>]+>", "", blurb)).split())
        indent = "  " * max(depth - 1, 0)
        line = f"{indent}- **{title}**" if depth <= 1 else f"{indent}- {title}"
        line += f" — {blurb}" if blurb else ""
        out.append(f"{line} `{href}`")
    return "\n".join(out) + "\n"


# -------------------------------------------------------------- packages.md

PKG_ENTRY_RE = re.compile(
    r'<li><a title="([^"]*)" href="\.\./\.\./([^/]+)/html/index\.html">[^<]+</a>(.*?)</li>',
    re.S,
)
THEME_RE = re.compile(r"<h2>(.*?)</h2>", re.S)


def gen_packages(src: Path, loaded: list[str]) -> str:
    text = (src / PACKAGES_PAGE).read_text(errors="replace")
    marks = [(m.start(), " ".join(html.unescape(re.sub(r"<[^>]+>", "", m.group(1))).split()))
             for m in THEME_RE.finditer(text)]
    marks.append((len(text), None))
    blocks, total, starred_total, bolt_total = [], 0, 0, 0
    for (start, theme), (end, _) in zip(marks, marks[1:]):
        section = text[start:end]
        entries = []
        for blurb, pkg, rest in PKG_ENTRY_RE.findall(section):
            starred = "GoldStar" in rest
            loaded_mark = pkg in loaded
            bolt_total += loaded_mark
            suffix = ""
            if loaded_mark:
                suffix += " ⚡"
            if starred:
                suffix += " ⭐"
            entries.append(
                f"- **{pkg}** — {' '.join(html.unescape(blurb).split())}" + suffix
            )
            total += 1
            starred_total += starred
        if entries:
            blocks.append(f"## {theme}\n\n" + "\n".join(entries) + "\n")
    intro = (
        f"{total} packages ship with this Macaulay2 build ({starred_total} refereed ⭐, "
        f"{bolt_total} loaded at startup ⚡ — plus Core itself; ⚡ packages need NO "
        'loadPackage, their functions are available in a fresh session).\n'
        'Load any other package: `loadPackage "Name"`. If M2 answers\n'
        '"not reloaded; try Reload => true", it is ALREADY loaded — just use it\n'
        "(do not force-reload: M2's reload machinery breaks on some packages).\n\n"
    )
    return intro + "\n".join(blocks)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--m2", default="M2", help="Macaulay2 binary (default: M2 on PATH)")
    ap.add_argument("--docs", type=Path, help="path to .../Macaulay2Doc/html (default: derived from --m2)")
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parent.parent / "skills/macaulay2/references")
    args = ap.parse_args()

    src = args.docs or find_docs_root(args.m2)
    if not (src / "master.html").is_file():
        sys.exit(f"error: {src} has no master.html — wrong path?")
    version = m2_version(args.m2)
    loaded = default_loaded(args.m2)
    pairs = trees_in_scope(src, loaded)
    args.out.mkdir(parents=True, exist_ok=True)
    print(f"scope: Macaulay2 {version} = core + {len(pairs) - 1} default-loaded doc trees")

    artifacts = {
        "index.tsv": ("symbol-index (grep this to check a name exists)", gen_index(pairs)),
        "toc.md": ("thematic table of contents (core)", gen_toc(src)),
        "packages.md": ("bundled packages by theme", gen_packages(src, loaded)),
    }
    for name, (kind, body) in artifacts.items():
        content = header(kind, version, src, loaded)
        if name.endswith(".md"):  # blockquote header style for markdown
            content = "\n".join(f"> {l}" for l in content.splitlines() if l.startswith("#")) + "\n\n"
        (args.out / name).write_text(content + body)
        print(f"wrote {args.out / name}")


if __name__ == "__main__":
    main()
